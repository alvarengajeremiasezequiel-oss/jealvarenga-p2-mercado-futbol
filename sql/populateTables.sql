USE SCHEMA JUGADORES_FUTBOL_DB.RAW;

CREATE OR REPLACE FILE FORMAT ff_jugadores_csv
  TYPE = CSV
  FIELD_DELIMITER = ','
  SKIP_HEADER = 1
  NULL_IF = ('', 'NULL')
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  TRIM_SPACE = TRUE;

TRUNCATE TABLE STAGING_PLAYERS;
COPY INTO STAGING_PLAYERS
FROM @raw_data
FILE_FORMAT = (FORMAT_NAME = ff_jugadores_csv)
FILES = ('players.csv')
ON_ERROR = 'ABORT_STATEMENT';

MERGE INTO PLAYERS t
USING STAGING_PLAYERS s
ON t.player_id = s.player_id
WHEN NOT MATCHED THEN
    INSERT ALL BY NAME;

SELECT
    "number of rows inserted"
FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));




