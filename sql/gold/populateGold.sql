CREATE OR REPLACE TABLE JUGADORES_FUTBOL_DB.FCT_PLAYER_SEASON AS
SELECT *
FROM JUGADORES_FUTBOL_DB.SILVER.FCT_PLAYER_SEASON;


CREATE OR REPLACE TABLE JUGADORES_FUTBOL_DB.GOLD.DIM_SEASON AS
SELECT
    season,
    SUM(goals)                AS total_goals,
    SUM(assists)              AS total_assists,
    SUM(yellow_cards)         AS total_yellow_cards,
    SUM(red_cards)            AS total_red_cards,
    AVG(average_time)         AS avg_minutes_played,
    AVG(average_market_value) AS avg_market_value
FROM JUGADORES_FUTBOL_DB.SILVER.FCT_PLAYER_SEASON
GROUP BY season;


CREATE OR REPLACE TABLE JUGADORES_FUTBOL_DB.GOLD.DIM_PLAYER AS
SELECT *
FROM JUGADORES_FUTBOL_DB.SILVER.DIM_PLAYER;


CREATE OR REPLACE TABLE JUGADORES_FUTBOL_DB.GOLD.DIM_CLUB AS
SELECT *
FROM JUGADORES_FUTBOL_DB.SILVER.DIM_CLUB;


CREATE OR REPLACE TABLE JUGADORES_FUTBOL_DB.GOLD.DIM_COMPETITION AS
SELECT *
FROM JUGADORES_FUTBOL_DB.SILVER.DIM_COMPETITION;