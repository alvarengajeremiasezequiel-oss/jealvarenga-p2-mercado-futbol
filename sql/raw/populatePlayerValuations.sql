CREATE OR REPLACE TEMP TABLE TMP_PLAYER_VALUATIONS LIKE JUGADORES_FUTBOL_DB.RAW.PLAYER_VALUATIONS;
COPY INTO TMP_PLAYER_VALUATIONS
FROM @raw_data
FILE_FORMAT = (FORMAT_NAME = ff_jugadores_csv)
FILES = ('player_valuations.csv')
ON_ERROR = 'ABORT_STATEMENT';

MERGE INTO PLAYER_VALUATIONS t
USING TMP_PLAYER_VALUATIONS s
ON (t.player_id = s.player_id AND t.date = s.date)
WHEN NOT MATCHED THEN
    INSERT ALL BY NAME;

SELECT "number of rows inserted"
FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));