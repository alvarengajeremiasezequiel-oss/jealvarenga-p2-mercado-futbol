CREATE OR REPLACE TEMP TABLE TMP_COMPETITIONS LIKE JUGADORES_FUTBOL_DB.RAW.COMPETITIONS;
COPY INTO TMP_COMPETITIONS
FROM @raw_data
FILE_FORMAT = (FORMAT_NAME = ff_jugadores_csv)
FILES = ('competitions.csv')
ON_ERROR = 'ABORT_STATEMENT';

MERGE INTO COMPETITIONS t
USING TMP_COMPETITIONS s
ON t.competition_id = s.competition_id
WHEN NOT MATCHED THEN
    INSERT ALL BY NAME;

SELECT "number of rows inserted"
FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));