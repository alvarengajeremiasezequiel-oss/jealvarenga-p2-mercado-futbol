CREATE OR REPLACE TEMP TABLE TMP_CLUBS LIKE JUGADORES_FUTBOL_DB.RAW.CLUBS;
COPY INTO TMP_CLUBS
FROM @raw_data
FILE_FORMAT = (FORMAT_NAME = ff_jugadores_csv)
FILES = ('clubs.csv')
ON_ERROR = 'ABORT_STATEMENT';

MERGE INTO CLUBS t
USING TMP_CLUBS s
ON t.club_id = s.club_id
WHEN NOT MATCHED THEN
    INSERT ALL BY NAME;

SELECT "number of rows inserted"
FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));