CREATE OR REPLACE TEMP TABLE TMP_APPEARANCES LIKE JUGADORES_FUTBOL_DB.RAW.APPEARANCES;
TRUNCATE TABLE TMP_APPEARANCES;
COPY INTO TMP_APPEARANCES
FROM @raw_data
FILE_FORMAT = (FORMAT_NAME = ff_jugadores_csv)
FILES = ('appearances.csv')
ON_ERROR = 'ABORT_STATEMENT';

MERGE INTO APPEARANCES t
USING TMP_APPEARANCES s
ON t.appearance_id = s.appearance_id
WHEN NOT MATCHED THEN
    INSERT ALL BY NAME;

SELECT "number of rows inserted"
FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));